
"""hapdc.scan -- per-window association scan with a permutation null in the same space.

Design notes
------------
* Every statistic is evaluated for the observed phenotype and for `nperm`
  permutations of it inside the *same* LMM, so a statistic is always compared
  against a null generated by the identical computation. Comparing a scan
  statistic against a pointwise p-value distribution from a different space is
  not valid and is not done here.
* `HDCb` combines the additive and the diplotype statistic by ACAT with EQUAL
  weights. Equal weights are fixed before looking at data. A weighted variant is
  available for sensitivity analysis but is not the default, because weights
  tuned after inspecting the full data cannot be described as prespecified.
* `w_sizes` accepts a ladder. Combining across widths is done with `acat` at
  equal weights over the ladder, which is again prespecified.
"""
import json
import os
import time

import numpy as np
import scipy.linalg as _sla

from .core import (acat, f2p, jitter_blocks, lambda_gc, ld_blocks,
                   reml_delta, t2p, window_design, windows)

__all__ = ["Scan", "combine_across_widths"]

STATS = ("A_joint", "P1_sidak", "P1_acat", "D_acat", "HDCb", "HDCt",
         "CELL_F", "NADD_F", "NADD_FS", "SACAT", "OMNI")
# Primary statistic: OMNI = equal-weight ACAT of A_joint (haplotype-additive
# joint F), CELL_F (diplotype-cell joint F) and SACAT (ACAT of single-marker
# additive tests in the unit). NADD_F tests the cells given the additive
# haplotype model (non-additivity). Weights are fixed before any data are seen.


def _prep_scale(U, S, y, covar=None):
    """Rotate a phenotype onto the GRM eigenbasis and return (yr, w, one, delta).

    `covar` (n, c) adds fixed-effect covariates (e.g. principal components) to
    the intercept; `one` is then the whitened (n, 1 + c) fixed-effect design."""
    n = len(y)
    Ut = U.T
    yr = Ut @ y
    if covar is None or np.asarray(covar).size == 0:
        Xr = Ut @ np.ones(n)
    else:
        Xr = Ut @ np.column_stack([np.ones(n), np.asarray(covar, float)])
    dlt = reml_delta(yr, S, Xr)
    w = 1.0 / np.sqrt(S + dlt)
    one = Xr * w if Xr.ndim == 1 else Xr * w[:, None]
    return yr, w, one, dlt



def _colbasis(X, tol=1e-8):
    """Orthonormal basis of col(X) from a column-pivoted QR.

    Columns are scaled to unit norm first so the relative rank tolerance does
    not depend on the units of the design; the rank is the number of |R_jj|
    above tol * |R_00|. Deterministic up to rounding for well-separated ranks.
    """
    nr = np.sqrt((X * X).sum(0))
    ok = nr > 0
    Xs = X[:, ok] / nr[ok]
    Q, R, _ = _sla.qr(Xs, mode="economic", pivoting=True)
    dg = np.abs(np.diag(R))
    r = int((dg > tol * dg[0]).sum()) if dg.size else 0
    return Q[:, :r]

class Scan:
    """Genome-wide (or region-wide) window scan for one trait.

    Parameters
    ----------
    H : (n_hap, m) int8
        Phased haplotypes, rows 2i / 2i+1 for individual i.
    meta : list of (chrom, id, pos, ref, alt)
    U, S : GRM eigenvectors / eigenvalues (n, n), (n,)
    y : (n,) phenotype, already aligned to the individuals in H.
    minf, minc : haplotype frequency and diplotype cell-count floors.
    covar : optional (n, c) fixed-effect covariates (e.g. top GRM eigenvectors).
    """

    def __init__(self, H, meta, U, S, y, minf=0.05, minc=5, seed=20261110, covar=None):
        self.H = H
        self.meta = meta
        self.U, self.S = U, S
        self.y = np.asarray(y, float)
        self.covar = covar
        self.minf, self.minc = minf, minc
        self.seed = seed
        n = len(self.y)
        self.n = n
        self.yr, self.w, self.one, self.delta = _prep_scale(U, S, self.y, covar)
        if self.one.ndim == 1:
            self.q0 = self.one / np.linalg.norm(self.one)
            self.Q0 = self.q0[:, None]
        else:
            self.Q0 = np.linalg.qr(self.one)[0]
            self.q0 = None
        self.nfix = self.Q0.shape[1]
        self.G = (H[0::2, :].astype(np.float32) + H[1::2, :].astype(np.float32))
        self._perm = None
        self._UG = None

    def _p0(self, X):
        """Residualise columns of X on the fixed effects (intercept [+ covariates])."""
        if self.nfix == 1:
            return X - np.outer(self.q0, self.q0 @ X)
        return X - self.Q0 @ (self.Q0.T @ X)

    def _projG(self, s=None, e=None):
        """U.T @ G restricted to markers [s, e).

        The projection is cached lazily in column blocks of 2048 markers,
        so a scan that touches a short region (a parallel chunk of a chromosome)
        no longer materialises the full n x m float64 projection (1.8 GB for
        2,504 x 97k). Column-wise identical to `U.T @ G[:, s:e]`.
        """
        m = self.G.shape[1]
        if s is None:
            s, e = 0, m
        bs = 2048
        b0, b1 = s // bs, (e - 1) // bs
        if self._UG is None or not isinstance(self._UG, dict):
            self._UG = {}
        for b in range(b0, b1 + 1):
            if b not in self._UG:
                self._UG[b] = self.U.T @ np.asarray(self.G[:, b * bs:min(m, (b + 1) * bs)], dtype=np.float64)
        if b0 == b1:
            return self._UG[b0][:, s - b0 * bs:e - b0 * bs]
        return np.hstack([self._UG[b] for b in range(b0, b1 + 1)])[:, s - b0 * bs:e - b0 * bs]

    def set_phenotype(self, y):
        """Replace the phenotype and recompute only the phenotype-dependent state.

        The genotype projection `Ut @ G` depends solely on G, so it is left intact:
        a permutation study reuses one 891 MB cache instead of rebuilding it per
        replicate. `_perm`, if set, is preserved.
        """
        self.y = np.asarray(y, float)
        if len(self.y) != self.n:
            raise ValueError("phenotype length %d != %d" % (len(self.y), self.n))
        self.yr, self.w, self.one, self.delta = _prep_scale(self.U, self.S, self.y, self.covar)
        if self.one.ndim == 1:
            self.q0 = self.one / np.linalg.norm(self.one)
            self.Q0 = self.q0[:, None]
        else:
            self.Q0 = np.linalg.qr(self.one)[0]
            self.q0 = None
        self.nfix = self.Q0.shape[1]
        return self

    def permute(self, nperm):
        rng = np.random.default_rng(self.seed)
        PM = np.stack([rng.permutation(self.n) for _ in range(nperm)], 1)
        self._perm = PM
        self.nperm = nperm
        return self

    def _design_matrix(self, rows, B):
        """Raw rotated phenotypes for observed (col 0) and permuted columns."""
        if self._perm is None:
            Y = self.yr[:, None]
        else:
            Y = np.column_stack([self.yr, self.yr[self._perm]])
        return Y * self.w[:, None]

    def run(self, w_size=None, w_step=None, lo=None, hi=None, verbose=True,
            blocks=None, need=None, batch=256):
        """Scan one window width, or a supplied block partition, over the markers.

        Passing `blocks` replaces the fixed-width window construction with an
        explicit partition (e.g. from `core.ld_blocks`), so the same statistics,
        the same LMM and the same permutation null are evaluated on LD-defined
        units instead of fixed-width ones. Nothing else in the scan changes.
        """
        chrom = [m[0] for m in self.meta]
        wins = list(blocks) if blocks is not None else windows(chrom, w_size, w_step)
        starts = [s for s, _ in wins]
        ceil = len(wins) if hi is None else min(hi, len(wins))
        lo = 0 if lo is None else lo
        idx = list(range(lo, ceil))

        YS = self._design_matrix(None, 0)
        B = YS.shape[1]
        n = self.n
        nf = self.nfix
        Ut = self.U.T
        R0 = self._p0(YS)
        rss0 = (R0 * R0).sum(0)

        P = {k: np.ones((len(idx), B)) for k in STATS}
        nk_ = np.zeros(len(idx), int)
        nc_ = np.zeros(len(idx), int)
        t0 = time.time()
        # optional statistics can be skipped: `need` lists the ones the
        # caller reads; the core four (A_joint, SACAT, CELL_F, NADD_F) and OMNI
        # are always computed. Results of computed statistics are unchanged.
        need = set(STATS) if need is None else set(need)
        do_dac = bool(need & {"D_acat", "HDCb", "HDCt"})
        do_p1 = do_dac or bool(need & {"P1_sidak", "P1_acat"})
        do_nfs = "NADD_FS" in need
        designs = {}

        def _prefetch(c0):
            # Rotate the haplotype and diplotype designs of `batch` units with one
            # matrix product: U'X for many units at once is compute-bound, while
            # one product per unit re-reads the n x n eigenvector matrix each time.
            designs.clear()
            cols, spans = [], []
            for wi in idx[c0:c0 + batch]:
                s_, e_ = wins[wi]
                d_ = window_design(self.H[:, s_:e_], self.minf, self.minc)
                designs[wi] = d_
                if d_["nk"] >= 2:
                    j0 = sum(x.shape[1] for x in cols)
                    cols.append(d_["dos"])
                    if d_["ncell"]:
                        cols.append(d_["C"])
                    spans.append((wi, j0, d_["nk"], d_["ncell"]))
            if cols:
                R = Ut @ np.hstack(cols)
                for wi, j0, nk0, nc0 in spans:
                    designs[wi]["Ud"] = R[:, j0:j0 + nk0]
                    designs[wi]["Uc"] = R[:, j0 + nk0:j0 + nk0 + nc0] if nc0 else np.zeros((n, 0))

        for c, wi in enumerate(idx):
            if c % batch == 0:
                _prefetch(c)
            s, e = wins[wi]
            d = designs[wi]
            nk = d["nk"]
            nk_[c] = nk
            nc_[c] = d["ncell"]
            # --- SACAT: single-marker additive tests in the unit, ACAT-combined
            Gw = self._projG(s, e) * self.w[:, None]
            Gw = self._p0(Gw)
            gn = (Gw * Gw).sum(0)
            gok = gn > 1e-8 * max(float(gn.max()), 1e-30)
            if gok.any():
                bg = (Gw[:, gok].T @ R0) / gn[gok][:, None]
                rg = np.clip(rss0[None, :] - bg * bg * gn[gok][:, None], 1e-300, None)
                tg = bg / np.sqrt(rg / (n - nf - 1) / gn[gok][:, None])
                pg = np.clip(t2p(tg, n - nf - 1), 1e-300, 1 - 1e-12)
                P["SACAT"][c] = pg[0] if pg.shape[0] == 1 else acat(pg, np.ones(pg.shape[0]))
            if nk < 2:
                P["OMNI"][c] = P["SACAT"][c]
                continue
            Ud = d["Ud"]
            Uc = d["Uc"]
            Xd = Ud * self.w[:, None]

            # --- joint haplotype test (A_joint): full model vs intercept only
            Q, Rr = np.linalg.qr(np.column_stack([self.one, Xd]))
            keepc = np.abs(np.diag(Rr)) > 1e-8 * np.abs(Rr[0, 0])
            Q = Q[:, keepc]
            k = Q.shape[1]
            RY = YS - Q @ (Q.T @ YS)
            rss1 = (RY * RY).sum(0)
            df2 = n - k
            dfa = k - nf
            if dfa > 0:
                F = ((rss0 - rss1) / dfa) / (rss1 / df2)
                P["A_joint"][c] = np.clip(f2p(F, dfa, df2), 1e-300, 1.0)

            if do_p1:
                # --- per-haplotype additive marginal, Sidak over the window (P1)
                xa = self._p0(Xd)
                nrm = (xa * xa).sum(0)
                ok = nrm > 1e-10
                b = np.zeros((Xd.shape[1], B))
                b[ok] = (xa[:, ok].T @ R0) / nrm[ok][:, None]
                rssa = np.clip(rss0[None, :] - b * b * nrm[:, None], 0, None)
                tv = np.zeros_like(b)
                good = ok[:, None] & (rssa > 0)
                tv[good] = b[good] / np.sqrt(rssa[good] / (n - nf - 1) / np.broadcast_to(nrm[:, None], b.shape)[good])
                pa = t2p(tv, n - nf - 1)
                pmin = pa.min(0)
                ps = -np.expm1(nk * np.log1p(-np.clip(pmin, 0, 1 - 1e-16)))
                P["P1_sidak"][c] = np.clip(ps, 1e-300, 1.0)
                # --- P1_acat: the same per-haplotype marginals, fused by ACAT
                # instead of collapsed to the smallest one. Shares every
                # intermediate with P1_sidak, so this adds no arithmetic.
                if ok.any():
                    pao = np.clip(pa[ok], 1e-300, 1 - 1e-12)
                    P["P1_acat"][c] = (pao[0] if pao.shape[0] == 1
                                       else acat(pao, np.ones(pao.shape[0])))
            # --- diplotype test (D_acat): cells of the joint genotype, ACAT over cells
            if do_dac and d["ncell"] > 1:
                Xc0 = Uc * self.w[:, None]
                Xc = Xc0 - Q @ (Q.T @ Xc0)
                ncx = (Xc * Xc).sum(0)
                okc = ncx > 1e-6 * np.maximum((Xc0 * Xc0).sum(0), 1e-30)
                if okc.any():
                    s2 = rss1 / (df2 - 1)
                    z = (Xc[:, okc].T @ RY) / np.sqrt(s2[None, :] * ncx[okc][:, None])
                    pc = t2p(z, df2 - 1)
                    dac = acat(np.clip(pc, 1e-300, 1.0), np.ones(pc.shape[0]))
                    P["D_acat"][c] = dac
                    # equal-weight combination: prespecified
                    P["HDCb"][c] = acat(np.vstack([ps, dac]), np.array([1.0, 1.0]))
                    # weighted variant, kept only for sensitivity analysis
                    P["HDCt"][c] = acat(np.vstack([ps, dac]), np.array([0.85, 0.15]))
            # --- CELL_F: joint F over diplotype cells vs intercept only
            parts = [P["A_joint"][c], P["SACAT"][c]]
            if d["ncell"] >= 2:
                Xc_ = Uc * self.w[:, None]
                Qc, Rc = np.linalg.qr(np.column_stack([self.one, Xc_]))
                kc = np.abs(np.diag(Rc)) > 1e-8 * np.abs(Rc[0, 0])
                Qc = Qc[:, kc]
                kcell = Qc.shape[1]
                if kcell > nf and n - kcell > 0:
                    RYc = YS - Qc @ (Qc.T @ YS)
                    rssc = (RYc * RYc).sum(0)
                    Fc = ((rss0 - rssc) / (kcell - nf)) / (rssc / (n - kcell))
                    P["CELL_F"][c] = np.clip(f2p(Fc, kcell - nf, n - kcell), 1e-300, 1.0)
                    parts.append(P["CELL_F"][c])
                # --- NADD_F: cells given the additive haplotype model
                # Column space from a column-pivoted QR. [1, Xd, Xc] is rank
                # deficient by construction (dosages sum to 2, cells sum to 1), and an
                # unpivoted QR then assigns arbitrary, rounding-dependent directions
                # to the dependent columns, so dropping them lost part of span(Xc)
                # in a platform-dependent way. The pivoted basis spans exactly
                # col([1, Xd, Xc]).
                Qf = _colbasis(np.column_stack([self.one, Xd, Xc_]))
                kfull = Qf.shape[1]
                if kfull > k and n - kfull > 0:
                    RYf = YS - Qf @ (Qf.T @ YS)
                    rssf = (RYf * RYf).sum(0)
                    Fn = ((rss1 - rssf) / (kfull - k)) / (rssf / (n - kfull))
                    P["NADD_F"][c] = np.clip(f2p(Fn, kfull - k, n - kfull), 1e-300, 1.0)
                if do_nfs:
                    # --- NADD_FS (addendum NF): cells given haplotype dosages AND all
                    # single-marker dosages of the unit (additive closure)
                    Xg = self._projG(s, e) * self.w[:, None]
                    Qa = _colbasis(np.column_stack([self.one, Xd, Xg])); kadd = Qa.shape[1]
                    Qb = _colbasis(np.column_stack([self.one, Xd, Xg, Xc_])); kall = Qb.shape[1]
                    if kall > kadd and n - kall > 0:
                        RYa = YS - Qa @ (Qa.T @ YS); rssa_ = (RYa * RYa).sum(0)
                        RYb = YS - Qb @ (Qb.T @ YS); rssb_ = (RYb * RYb).sum(0)
                        Fs = ((rssa_ - rssb_) / (kall - kadd)) / (rssb_ / (n - kall))
                        P["NADD_FS"][c] = np.clip(f2p(Fs, kall - kadd, n - kall), 1e-300, 1.0)
            pp = np.clip(np.vstack(parts), 1e-300, 1 - 1e-12)
            P["OMNI"][c] = acat(pp, np.ones(pp.shape[0]))
            if verbose and c % 500 == 0 and c:
                print("  win %d/%d nk=%d ncell=%d %.0fs" % (c, len(idx), nk, d["ncell"], time.time() - t0),
                      flush=True)

        return dict(w_size=w_size, w_step=w_step, lo=lo, hi=ceil, nwin=len(idx),
                    design="blocks" if blocks is not None else "fixed",
                    starts=[starts[i] for i in idx],
                    nk=nk_, ncell=nc_, P=P, B=B, delta=self.delta,
                    elapsed=time.time() - t0, stats=list(STATS))

    def calibrate(self, res, stats=None):
        """Pointwise false-positive rate and a scan-wide threshold from the null columns."""
        stats = stats or [s for s in STATS if s in res["P"]]
        out = {}
        for k in stats:
            M = res["P"][k]
            if M.shape[1] < 2:
                out[k] = dict(fpr=float("nan"), thr=float("nan"), n_below=int((M[:, 0] <= 0.05).sum()))
                continue
            nul = M[:, 1:]
            fpr = float((nul <= 0.05).mean())
            mins = nul.min(0)
            thr = float(np.quantile(mins, 0.05))
            out[k] = dict(fpr=fpr, thr=thr, median_null_min=float(np.median(mins)),
                          n_below=int((M[:, 0] <= thr).sum()),
                          n_perm=int(nul.shape[1]))
        return out


def combine_across_widths(results, weights=None):
    """ACAT-combine one statistic across a window-width ladder, equal weights by default."""
    stat_sets = [r for r in results if r is not None]
    if not stat_sets:
        return None
    keys = [k for k in STATS if all(k in r["P"] for r in stat_sets)]
    nup = min(r["P"][k].shape[0] for r in stat_sets for k in keys)
    out = {}
    for k in keys:
        stack = np.stack([r["P"][k][:nup] for r in stat_sets], 0)  # (nwidth, nwin, B)
        w = np.ones(len(stat_sets)) if weights is None else np.asarray(weights, float)
        # ACAT over widths, vectorised over (window, column)
        Pw = stack.reshape(len(stat_sets), -1)
        out[k] = acat(Pw, w).reshape(nup, -1)
    return out
